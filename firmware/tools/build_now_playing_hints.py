def render_header() -> str:
    """Return the complete deterministic C++ header without writing files.

    Tests call this pure renderer; only the explicit CLI `build()` writes
    the production header. A mismatched header must fail, not self-repair
    while the test is running.
    """
    curated = {}
    for line in (ROOT / "data/jazz-editorial-bios.tsv").read_text("utf-8").splitlines():
        key, bio, source = line.split("\t")
        assert key not in curated and bio and source.startswith("https://")
        curated[key] = bio
    assert len(curated) == len(CAPTIONS) == 63, (len(curated), len(CAPTIONS))
    assert set(curated) == set(CAPTIONS), (
        sorted(set(curated) - set(CAPTIONS)), sorted(set(CAPTIONS) - set(curated))
    )
    researched = {}
    for line in (ROOT / "data/jazz-researched-context.tsv").read_text("ascii").splitlines():
        key, bio, source = line.split("\t")
        assert key not in researched and key not in curated
        assert bio.isascii() and 80 <= len(bio) <= 180
        assert source.startswith("https://")
        researched[key] = bio
    assert len(researched) == len(RESEARCH_CAPTIONS), (
        len(researched), len(RESEARCH_CAPTIONS))
    assert set(researched) == set(RESEARCH_CAPTIONS), (
        sorted(set(researched)-set(RESEARCH_CAPTIONS)),
        sorted(set(RESEARCH_CAPTIONS)-set(researched)))
    encyclopedia = {}
    for line in (ROOT / "data/jazz-encyclopedia.tsv").read_text("ascii").splitlines():
        key, name, summary, album, source = line.split("\t")
        encyclopedia[key] = (name, summary)
    rows = []
    all_captions = CAPTIONS | RESEARCH_CAPTIONS
    all_bios = curated | researched
    for key in sorted(all_captions):
        caption = all_captions[key]
        assert key in encyclopedia
        name, summary = encyclopedia[key]
        # Every flash preview must actually match the corresponding extended
        # editorial note; never attach it to a generic Wikidata label.
        assert len(summary) >= 80 and summary == all_bios[key], key
        assert all(ord(c) < 127 for c in name + caption), key
        # Current radio overlay uses one 222px line; 36 ASCII chars fit in
        # the pinned Cardputer font without clipping or ellipses.
        assert 10 <= len(caption) <= 36, (key, caption)
        assert re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", key)
        rows.append(f"      {{{dumps(name)}, {dumps(caption)}}},")
    source = (
        "// SPDX-License-Identifier: MIT\n"
        "// Generated by tools/build_now_playing_hints.py from 63 preserved\n"
        f"// editorial + {len(RESEARCH_CAPTIONS)} researched Jazz Notes. Exact ICY matches only.\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "namespace pocketjazz {\n"
        "class JazzNowPlaying {\n"
        " public:\n"
        f"  static constexpr size_t kCuratedCount = {len(all_captions)};\n"
        "  static const char* hint(const char* artist) {\n"
        "    if (!artist || !*artist) return nullptr;\n"
        "    struct Record { const char* name; const char* shortBio; };\n"
        "    static const Record kCurated[kCuratedCount] = {\n"
        + "\n".join(rows) + "\n"
        "    };\n"
        "    for (const auto& entry : kCurated)\n"
        "      if (sameName(artist, entry.name)) return entry.shortBio;\n"
        "    return nullptr;\n"
        "  }\n"
        " private:\n"
        "  static bool sameName(const char* a, const char* b) {\n"
        "    for (; *a && *b; ++a, ++b) {\n"
        "      uint8_t x = static_cast<uint8_t>(*a);\n"
        "      uint8_t y = static_cast<uint8_t>(*b);\n"
        "      if (x >= 'A' && x <= 'Z') x += 'a' - 'A';\n"
        "      if (y >= 'A' && y <= 'Z') y += 'a' - 'A';\n"
        "      if (x != y) return false;\n"
        "    }\n"
        "    return !*a && !*b;\n"
        "  }\n"
        "};\n"
        "} // namespace pocketjazz\n"
    )
    return source


def build() -> None:
    target = ROOT / "PocketJazzRadio/JazzNowPlaying.h"
    source = render_header()
    target.write_text(source, encoding="ascii", newline="\n")
    print("NOW_PLAYING_HINTS_REGENERATED", len(CAPTIONS)+len(RESEARCH_CAPTIONS),
          "entries", target.stat().st_size, "bytes")


if __name__ == "__main__":
    build()
